#!/usr/bin/env python3
"""Generates src/Croft.Web/wwwroot/branding-default/fallback-banner.svg: the Government / 42nd /
Black Watch tartan, the framework's default fallback banner (brief 10b item 4).

    python3 dev/black-watch-banner.py            # rewrite the file
    python3 dev/black-watch-banner.py --stdout   # print it instead

The sett is the Scottish Register of Tartans' half-sett (reference 277, "Grant Hunting or Black
Watch", as reproduced at tartanflag.com). The slashes are pivots: the sett runs to the end, then
mirrors back, so the full sett is the half-sett followed by its reverse without the two pivot
stripes repeated. One SVG unit is one thread: the full sett is 416 threads, so the tile is
416 x 416 units, repeated by the existing `background-size: 180px` rule.

Built the way the Crawford tartan is: the warp is drawn as horizontal bands, the weft as vertical
bands under a 45-degree twill mask (a pattern of 1-unit stripes, rotated, used as a mask).
"""
import pathlib
import sys

# The colours, in one place (modern colourway, close to the Register's).
DARK_BLUE = "#1C2841"
BLACK = "#0E0E10"
GREEN = "#1F4730"

COLOUR = {"DB": DARK_BLUE, "K": BLACK, "G": GREEN}
HALF_SETT = "DB/44 K4 DB4 K4 DB4 K32 G32 K4 G32 K32 DB32 K4 DB/4"


def full_sett(half: str) -> list[tuple[str, int]]:
    stripes = [(token.replace("/", "").rstrip("0123456789"), int(token.replace("/", "").lstrip("DBKG")))
               for token in half.split()]
    # Mirror back from the last pivot to the first, without repeating either pivot stripe.
    return stripes + stripes[-2:0:-1]


def bands(sett: list[tuple[str, int]], horizontal: bool) -> str:
    out, at = [], 0
    for name, count in sett:
        if horizontal:
            out.append(f'<rect y="{at}" width="{size}" height="{count}" fill="{COLOUR[name]}"/>')
        else:
            out.append(f'<rect x="{at}" width="{count}" height="{size}" fill="{COLOUR[name]}"/>')
        at += count
    assert at == size
    return "".join(out)


sett = full_sett(HALF_SETT)
size = sum(count for _, count in sett)
assert size < 512, size

svg = f"""<svg xmlns="http://www.w3.org/2000/svg" width="{size}" height="{size}" viewBox="0 0 {size} {size}">
<!-- Government / 42nd / Black Watch tartan. Scottish Register of Tartans reference 277 ("Grant Hunting or Black Watch"); worn since 1739, designer unknown, so no copyright applies.
Thread count (half-sett, slashes are pivots): {HALF_SETT}
Source of the thread count: https://www.tartanflag.com, reproducing the Register's entry. One unit per thread; {size} threads make the full sett.
Colours: dark blue {DARK_BLUE}, black {BLACK}, green {GREEN}.
Generated by dev/black-watch-banner.py. -->
<defs><pattern id="t" width="2" height="2" patternUnits="userSpaceOnUse" patternTransform="rotate(45)"><rect width="1" height="2" fill="#fff"/></pattern><mask id="m" maskUnits="userSpaceOnUse" width="{size}" height="{size}"><rect width="{size}" height="{size}" fill="url(#t)"/></mask></defs>
<g id="warp">{bands(sett, True)}</g>
<g id="weft" mask="url(#m)">{bands(sett, False)}</g>
</svg>
"""

if "--stdout" in sys.argv:
    sys.stdout.write(svg)
else:
    target = pathlib.Path(__file__).resolve().parent.parent / "src/Croft.Web/wwwroot/branding-default/fallback-banner.svg"
    target.write_text(svg)
    print(f"wrote {target} ({len(svg.encode())} bytes)")
